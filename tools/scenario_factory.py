"""Generate independent v4 scenarios from declared parameters.

Why a generator rather than eight hand-written scenarios.

The confirmatory phase needs 120 independent scenarios, and the pilot needed
several.  Writing them by hand has two failure modes that a generator removes:

**Hand-tuning to pass the gate.**  Each scenario carries its own exposure
contract — the decisive propositions and the oracle's sufficiency requirements —
and a hand-written scenario can be quietly adjusted until its gate goes green.
Here the contract is *derived* from the same parameters that build the corpus, so
there is no separate surface to tune: change the event name and every proposition
referring to it changes with it.

**Undisclosed variation.**  "Independent scenarios" has to mean something
specific.  What varies between them is enumerated below; everything else is
shared by construction.  In particular the *structure* is identical — same
branch count, same slot index, same shared-context roles — so a difference in
outcome cannot be a difference in design shape.

What deliberately does NOT vary, because varying it would confound the contrast:

* the kind of manipulation (an appointment is rescheduled and the old date
  voided) — a scenario where the fact merely changed would be a different study;
* the pressure sentences (shared verbatim across scenarios, so pressure is the
  same manipulation everywhere);
* the slot's position, the shared-context role set, the tool set, the probe
  question form;
* the numeral style for the dates, so no scenario accidentally writes a date in a
  form the decisive-proposition terms cannot match.  The rendering conventions
  themselves are covered by tests.

What varies: event kind, participant role, the specific dates, the filler used
for the omit slot, and the distractor texts.  Each is a documented parameter.

The generated documents are natural language, and natural language cannot be
generated by a template without reading like one.  So the *text* is authored per
event kind in the tables below while the *structure* — which documents exist,
what role each plays, how the contract's terms derive from the event name — is
generated.  That split is the honest one: it keeps tuning out of the structure
while leaving the prose human-written.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date, timedelta
from typing import Sequence

