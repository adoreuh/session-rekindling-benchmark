from vela_lab.errors import ValidationError


@dataclass(frozen=True)
class EventProfile:
    """One event kind: what is being rescheduled, and the words that name it.

    ``referent`` and ``referent_long`` are the visible names of the event.  Every
    decisive proposition is built from these, which is what makes the contract
    non-tunable: the proposition "the event was cancelled" is
    ``(referent, cancel_word)`` for whichever event this profile describes.
    """

    profile_id: str
    referent: str            # short visible name, e.g. "签证面试"
    referent_long: str       # the way it is named at first mention
    holder: str              # who the appointment belongs to, e.g. "用户"
    office: str              # who issued the original confirmation
    office_short: str        # shorter form for title lines
    cancel_word: str         # "取消" or "作废"
    void_word: str           # the other one
    old_date: date
    new_date: date
    update_day: date         # when the notice arrives
    update_time: str = "09:00"
    booking_time: str = "上午 9 点"
    lead: str = ""           # one clause of context, used in the confirmation


def _md(value: date) -> str:
    """The spaced Chinese rendering used in visible text."""
    return f"{value.month} 月 {value.day} 日"


def _md_full(value: date) -> str:
    return f"{value.year} 年 {value.month} 月 {value.day} 日"


@dataclass(frozen=True)
class ScenarioVariant:
    """A scenario's parameters and its derived contract terms."""

    scenario_id: str
    profile: EventProfile
    filler_id: str
    shared_ids: tuple
    documents: tuple          # (doc_id, title, text, published_at, source)
    prefix_turns: tuple
    stable_material: tuple
    time_zone: str
    prefix_start: str
    elapsed_base_days: int
    # Which document is the authoritative evidence.  Defaults to the profile's
    # single notice; the temporal ladder overrides it because its corpus holds
    # one notice per stage and only the live stage's notice is the answer.
    # Declared last because a defaulted field may not precede a required one.
    gold_override: str = ""
    #: The date the authoritative evidence says is operative.
    #:
    #: Exists because the ladder's authoritative date changes with elapsed time
    #: while the profile's does not.  Every derived term that names "the current
    #: date" must read this field rather than ``profile.new_date``; using the
    #: profile's value under the ladder produced the same class of defect three
    #: times — the decisive propositions, the oracle sufficiency groups and the
    #: shared-context check all pointed at a date that was no longer operative.
    authoritative_date: date | None = None

    # ----------------------------------------------------------- derived terms

    @property
    def operative_date(self) -> date:
        """The date the live evidence makes current."""
        return self.authoritative_date or self.profile.new_date

    def event_referents(self) -> tuple:
        return (self.profile.referent, self.profile.referent_long)

    def decisive_propositions(self) -> tuple:
        """The propositions, built from the profile's vocabulary.

        Both referent spellings are registered, and both cancellation words.
        Registering only the short referent leaves a hole that is easy to miss
        because the gold notice happens to contain both forms: a leak phrased
        *only* with the long name would match no proposition and the gate would
        report it absent.  Measured, not assumed — a profile whose long name does
        not contain the short name as a substring ("德语语言水平考试" /
        "语言考试") shows the miss directly.

        Same failure mode as an exact-match tool-name check: a term list that
        knows one spelling detects only that spelling, so every recognised
        spelling is registered rather than the most convenient one.
        """
        p = self.profile
        current = _md(self.operative_date)
        names = tuple(dict.fromkeys((p.referent, p.referent_long)))
        propositions = []
        for index, name in enumerate(names):
            suffix = "" if index == 0 else f"_{index}"
            propositions.extend((
                {
                    "proposition_id": f"old_appointment_not_operative{suffix}",
                    "description": "the original appointment no longer stands, so "
                                   "arriving on the old date will not work",
                    "requires": (name, p.cancel_word),
                },
                {
                    "proposition_id": f"old_appointment_void{suffix}",
                    "description": "same statement, phrased with the other word",
                    "requires": (name, p.void_word),
                },
                {
                    "proposition_id": f"current_date_is_new{suffix}",
                    "description": "the operative date is the new one for this event",
                    "requires": (name, current),
                },
            ))
        propositions.append({
            "proposition_id": "old_confirmation_superseded",
            "description": "the old confirmation is replaced by the notice",
            "requires": ("预约", "替代旧确认单"),
        })
        return tuple(propositions)

    def oracle_required_groups(self) -> tuple:
        """What must survive into the request for delivery to count as sufficient.

        Groups are alternatives, not conjunctions: the authority requirement is
        satisfied by either name for the office, and demanding both would fail an
        adequate notice.
        """
        p = self.profile
        return (
            (p.referent, p.referent_long),
            (p.cancel_word, p.void_word),
            (_md(self.operative_date),),
            (p.office_short, p.office),
        )

    def neutral_material_ids(self) -> tuple:
        return tuple(doc_id for doc_id, *_ in self.documents
                     if doc_id != self.gold_id)

    @property
    def decoy_date(self) -> date:
        """A date that appears nowhere in the corpus.

        Used by the control condition that separates "the model followed the
        user's assertion" from "the model followed the stale shared document":
        with a decoy, an answer naming it cannot have come from the corpus.

        Deliberately a few days off the old date so it is a plausible booking
        (not an obviously absurd date, which the model would reject for that
        reason alone) while remaining absent from every document.  The
        constructor asserts that absence rather than trusting this comment.
        """
        return self.profile.old_date - timedelta(days=7)

    @property
    def gold_id(self) -> str:
        return self.gold_override or f"{self.profile.profile_id}_reschedule_notice"

    def prefix_start_instant(self) -> str:
        return f"{self.profile.old_date.year}-03-01T09:00:00+08:00"

    def update_instant(self) -> str:
        return (f"{self.profile.update_day.isoformat()}T"
                f"{self.profile.update_time}:00+08:00")


