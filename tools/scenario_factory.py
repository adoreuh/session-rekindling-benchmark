# ---------------------------------------------------------------------------
# The temporal ladder
# ---------------------------------------------------------------------------
#
# Why this exists.
#
# The v4 controlled-delivery design made the accessibility contrast clean by
# stating the delivered set outright (``deliver_ids``).  The cost is that elapsed
# time then changes *nothing observable*: the measured delivered set, the
# eligibility set and the natural ranking are identical at every elapsed point,
# and only the rendered date string differs.  ``tools/temporal_study.py`` measures
# exactly that.  A design whose temporal manipulation amounts to one date string
# cannot support a claim about elapsed world time.
#
# The fix is not to weaken the delivery control but to let the **world** change
# over time, through the registered schedule:
#
# * documents become available at their publication instants, so eligibility is a
#   function of elapsed time — this is what makes L2 (accessibility) measurable;
# * a later notice supersedes an earlier one, so *which answer is correct* is a
#   function of elapsed time — this is what makes L3 (behaviour) measurable.
#
# Note what is deliberately NOT used: temporal decay weights.  A uniform
# multiplicative decay applied to every candidate cancels out of the ranking
# (``S_i(t+Δ) = e^{-Δ/T}·S_i(t)``), so it cannot move the order at all.  Using it
# as the temporal manipulation would produce a knob that is provably inert.  The
# ladder uses publication timing, which genuinely changes what is reachable.
#
# Both mechanisms are properties of the registered world, so a run cannot tune
# them: the ladder is derived from the profile, and the contract terms travel
# with whichever notice is authoritative.


@dataclass(frozen=True)
class LadderStage:
    """One step of the ladder: a notice that becomes authoritative at an instant."""

    stage_id: str
    published_at: str        # when this notice becomes queryable
    authoritative_from: str  # when it becomes the operative answer
    voids: date              # the date this stage supersedes
    sets: date               # the date this stage makes current
    order: int               # tiebreak for same-instant publications


def build_ladder(profile: EventProfile, *, stages: int = 2,
                 gap_days: int = 14) -> tuple:
    """Derive the ladder stages for a profile.

    Derived rather than declared per scenario so that no scenario can be tuned to
    a convenient publication time.  The gap is a parameter of the design, not of
    the scenario's prose.
    """
    if stages < 1:
        raise ValidationError("a ladder needs at least one stage")
    out = []
    voids = profile.old_date
    sets = profile.new_date
    for index in range(stages):
        published_day = profile.update_day + timedelta(days=gap_days * index)
        out.append(LadderStage(
            stage_id=f"{profile.profile_id}_notice_{index + 1}",
            published_at=f"{published_day.isoformat()}T09:00:00+08:00",
            authoritative_from=f"{published_day.isoformat()}T09:00:00+08:00",
            voids=voids,
            sets=sets,
            order=index,
        ))
        voids, sets = sets, sets + timedelta(days=gap_days)
    return tuple(out)


def authoritative_stage(stages: Sequence[LadderStage], instant: str) -> LadderStage:
    """Which stage is operative at ``instant``.

    Falls back to the earliest stage for an instant before every publication, so
    a probe scheduled too early yields the first stage rather than raising — and
    the caller can compare the returned stage against the instant to see that it
    was not yet live.
    """
    live = [s for s in stages
            if parse_instant(s.authoritative_from) <= parse_instant(instant)]
    return live[-1] if live else stages[0]


def ladder_notice_text(profile: EventProfile, stage: LadderStage,
                       *, final: bool) -> str:
    """The notice text for a stage, worded like a real notice.

    ``final`` decides the closing sentence: a middle stage says a further update
    may follow, the last says this is the operative booking.  Stating a
    "no further changes" promise on a middle stage would contradict the next one.
    """
    opening = "通知" if stage.order == 0 else "补充通知"
    closing = ("请以本通知替代此前所有通知。" if not final
               else "这是目前唯一有效的预约日期，请以此为准。")
    return (
        f"{profile.office}{opening}：{profile.holder}的{profile.referent_long}时间调整，"
        f"原定 {_md(stage.voids)} {profile.booking_time}的安排已"
        f"{profile.cancel_word}并{profile.void_word}，现改为 {_md(stage.sets)} "
        f"{profile.booking_time}，地点不变。{_md(stage.sets)}是本次"
        f"{profile.referent}当前有效的预约日期。{closing}"
    )


@dataclass(frozen=True)
class LadderVariant:
    """A scenario variant positioned on the ladder.

    Carries both the base variant's structure and the stage that is operative at
    the probe instant, so the delivered slot and the correct answer are both
    functions of elapsed time rather than of the condition.
    """

    variant: ScenarioVariant
    stages: tuple
    stage: LadderStage
    stage_live: bool           # whether the operative stage had been published
    #: Earlier notices that must be delivered alongside the live one, so the
    #: update record is self-contained.
    #:
    #: Why this is needed.  A notice says "the previous arrangement is void",
    #: which is only interpretable if the material also shows what that previous
    #: arrangement was.  Delivering stage 2 alone produced exactly this defect:
    #: the notice voided 6-25 while nothing in the delivered material had ever
    #: stated 6-25, so the condition measured "an update citing a state the
    #: material lacks" rather than a clean temporal update.  One route spotted the
    #: gap and asked the user to verify; the other adopted the notice.  Both are
    #: defensible readings of a broken record, which is why the record must be
    #: complete before the condition can be called a temporal manipulation.
    preceding_ids: tuple = ()

    @property
    def correct_date(self) -> date:
        return self.stage.sets

    def gold_id(self) -> str:
        return self.stage.stage_id

    def describe(self) -> dict:
        return {
            "scenario_id": self.variant.scenario_id,
            "profile_id": self.variant.profile.profile_id,
            "stage": self.stage.stage_id,
            "stage_order": self.stage.order,
            "stage_live": self.stage_live,
            "published_at": self.stage.published_at,
            "correct_date": self.correct_date.isoformat(),
            "voids": self.stage.voids.isoformat(),
        }


def build_ladder_variant(*, profile: EventProfile, filler_id: str,
                         instant: str) -> LadderVariant:
    """Assemble the variant whose authoritative notice is the one live at ``instant``.

    The corpus gains one document per ladder stage, so documents published after
    the probe instant are present in the registry but **not eligible** — which is
    the mechanism that makes accessibility a function of elapsed time.  A
    document that is registered but unpublished is exactly the case
    ``EvidenceCorpus`` already models, so no new machinery is needed.
    """
    stages = build_ladder(profile)
    stage = authoritative_stage(stages, instant)
    base = build_variant(
        scenario_id=f"ladder-{profile.profile_id}",
        profile=profile, filler_id=filler_id,
    )

    preceding = tuple(item.stage_id for item in stages if item.order < stage.order)

    notices = []
    for index, item in enumerate(stages):
        notices.append((
            item.stage_id,
            f"官方通知：原{profile.referent}预约{'取消并改期' if index == 0 else '再次调整'}",
            ladder_notice_text(profile, item, final=(index == len(stages) - 1)),
            item.published_at,
            f"{profile.office}官方改期通知",
        ))

    # Replace the base scenario's single notice with the whole ladder, and drop
    # the base gold doc so the only gold is the authoritative stage.
    kept = tuple(d for d in base.documents if d[0] != base.gold_id)
    documents = kept + tuple(notices)

    # The preceding notices join the shared context so the update record reads end
    # to end.  They go to *both* conditions, so the accessibility contrast is
    # untouched, while the material now shows the state the live notice voids.
    #
    # Why this is required rather than cosmetic: delivering stage 2 alone produced
    # a notice that voids 6-25 while nothing delivered had ever stated 6-25.  The
    # condition then measured "an update citing a state the material lacks", and one
    # route responded by asking the user to verify the record while the other
    # adopted the notice — two defensible readings of a broken record, neither of
    # them the temporal update the condition claimed to test.
    #
    # Sharing them is safe because a preceding notice states an *already
    # superseded* date, never the live one; `_validate` below enforces that, since
    # a shared document carrying the current answer would collapse the manipulation.
    shared_with_chain = tuple(reversed(preceding)) + tuple(base.shared_ids)
    staged = ScenarioVariant(
        scenario_id=base.scenario_id,
        profile=base.profile,
        filler_id=base.filler_id,
        shared_ids=shared_with_chain,
        documents=documents,
        prefix_turns=base.prefix_turns,
        stable_material=base.stable_material,
        time_zone=base.time_zone,
        prefix_start=base.prefix_start,
        elapsed_base_days=base.elapsed_base_days,
        # The live stage's notice is the authoritative evidence.  Naming it here
        # is what keeps the contract, the pair and the gold marker pointing at one
        # document instead of three notices.
        gold_override=stage.stage_id,
        # The live stage decides which date is current, and every derived term
        # reads it from here.
        authoritative_date=stage.sets,
    )

    # Validate the assembled variant: the base validation never ran on it, because
    # it is constructed directly rather than through ``build_variant``.  The check
    # that matters here is that no shared document carries the live answer.
    _validate(staged)

    live = parse_instant(stage.published_at) <= parse_instant(instant)
    return LadderVariant(
        variant=staged, stages=stages, stage=stage, stage_live=live,
        preceding_ids=preceding,
    )
