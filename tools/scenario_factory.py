def _validate(variant: ScenarioVariant) -> None:
    """Fail closed on a variant the gate could not check.

    These are the conditions the exposure gate relies on, so an unbuildable
    variant must be caught here rather than surfacing as a gate failure 480
    executions later.  Each check names the invariant, not just the symptom.
    """
    ids = [doc_id for doc_id, *_ in variant.documents]
    if len(set(ids)) != len(ids):
        raise ValidationError(f"scenario {variant.scenario_id}: duplicate doc ids")
    if variant.filler_id not in ids:
        raise ValidationError(
            f"scenario {variant.scenario_id}: filler {variant.filler_id!r} is not "
            f"in the corpus"
        )
    if variant.gold_id not in ids:
        raise ValidationError(
            f"scenario {variant.scenario_id}: gold {variant.gold_id!r} missing"
        )
    if set(variant.shared_ids) & {variant.gold_id, variant.filler_id}:
        raise ValidationError(
            f"scenario {variant.scenario_id}: the slot material is already in the "
            "shared context, so the slot is not what makes it available"
        )
    for doc_id in variant.shared_ids:
        if doc_id not in ids:
            raise ValidationError(
                f"scenario {variant.scenario_id}: shared id {doc_id!r} missing"
            )

    # The filler must assert no date.  Reusing the access_pair guard rather than
    # re-implementing it keeps one definition of "asserts a date".
    from tools.access_pair import DATE_HINTS

    bodies = {doc_id: text for doc_id, _, text, _, _ in variant.documents}
    filler_hits = [hint for hint in DATE_HINTS if hint in bodies[variant.filler_id]]
    if filler_hits:
        raise ValidationError(
            f"scenario {variant.scenario_id}: filler asserts a date ({filler_hits}); "
            "a filler that names a date is misleading evidence, not neutral"
        )

    # The new date must not appear in any shared document, or the omit condition
    # would receive the answer through the shared context.
    new_text = _md(variant.operative_date)
    for doc_id in variant.shared_ids:
        if new_text in bodies[doc_id]:
            raise ValidationError(
                f"scenario {variant.scenario_id}: shared document {doc_id!r} "
                f"contains the new date; the shared context must not carry the "
                f"answer or the slot is not the manipulation"
            )

    # The notice must actually void the old date, in a word the propositions know.
    notice = bodies[variant.gold_id]
    if not any(word in notice for word in
               (variant.profile.cancel_word, variant.profile.void_word)):
        raise ValidationError(
            f"scenario {variant.scenario_id}: the notice does not void the old "
            "arrangement; a new value alone would not conflict with the user's claim"
        )

    # The decoy date is the control condition's whole mechanism, so its absence
    # has to be a checked fact.  If it appeared anywhere in the corpus — including
    # a title or a source label — an answer naming it could not be attributed to
    # the user's assertion, and the control would silently stop controlling.
    decoy = _md(variant.decoy_date)
    if not decoy:
        raise ValidationError(f"scenario {variant.scenario_id}: empty decoy date")
    for doc_id, title, text, _, source in variant.documents:
        blob = f"{title} {text} {source}"
        if decoy in blob:
            raise ValidationError(
                f"scenario {variant.scenario_id}: the decoy date {decoy!r} appears "
                f"in {doc_id!r}, so the control condition could not distinguish "
                "the user's assertion from a corpus document"
            )
    if decoy == _md(variant.profile.old_date) or decoy == _md(variant.operative_date):
        raise ValidationError(
            f"scenario {variant.scenario_id}: the decoy date must differ from both "
            "the old and the new date"
        )


